-- =====================================================================
-- Stride & Soul — BigQuery dataset and tables
-- Run 1 of 5. Paste into BigQuery Studio and run. Safe to re-run.
--
-- Migrated from the Calzados Djohn Supabase scripts (00-10).
-- BigQuery has no sequences, triggers, CHECK constraints or row locks,
-- so every business rule that lived in those now lives in the stored
-- procedures of 03_procedures.sql (one transaction per operation).
-- =====================================================================

CREATE SCHEMA IF NOT EXISTS stride_soul
OPTIONS (location = 'US', description = 'Stride & Soul: operational data for the Sole sales agent');

-- ---------------------------------------------------------------------
-- Settings that differ by market. Read by the procedures.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS stride_soul.settings (
  key         STRING NOT NULL,
  value       STRING NOT NULL,
  description STRING
);

-- ---------------------------------------------------------------------
-- Counters: BigQuery's replacement for Postgres sequences.
-- Every procedure that issues a number UPDATEs its counter row inside its
-- transaction. Two transactions that touch the same counter conflict and
-- BigQuery aborts one of them, so numbers are never duplicated (n8n retries).
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS stride_soul.counters (
  name  STRING NOT NULL,   -- ticket | support_case
  value INT64  NOT NULL
);

-- ---------------------------------------------------------------------
-- Catalog: one row per product variant (model + colour + subculture).
-- Stock is per variant, not per size (same model as the original).
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS stride_soul.catalog (
  product_id  INT64     NOT NULL,
  model       STRING    NOT NULL,
  brand       STRING    NOT NULL,
  type        STRING    NOT NULL,   -- sneakers | shoes | ankle boots | boots | sandals
  subculture  STRING    NOT NULL,   -- punk | hardcore | straight edge | emo | goth | metal
  size_range  STRING    NOT NULL,   -- EU sizes, e.g. '35-44'
  color       STRING    NOT NULL,
  price       NUMERIC   NOT NULL,   -- final price, tax included
  stock       INT64     NOT NULL,
  created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP()
)
CLUSTER BY subculture, type;

-- ---------------------------------------------------------------------
-- Policies: ready-to-send answers the agent looks up by topic.
-- Topics prefixed internal_ are agent behaviour, never quoted to customers.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS stride_soul.shipping_policy (
  topic   STRING NOT NULL,
  content STRING NOT NULL
);

CREATE TABLE IF NOT EXISTS stride_soul.return_policy (
  topic   STRING NOT NULL,
  content STRING NOT NULL
);

-- ---------------------------------------------------------------------
-- Sales: positive quantity = sale, negative quantity = refund (credit note).
-- ticket_no is generated by sp_register_sale / sp_process_refund.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS stride_soul.sales (
  sale_id          STRING    NOT NULL,   -- GENERATE_UUID()
  ticket_seq       INT64     NOT NULL,   -- gapless counter, unique
  ticket_no        STRING    NOT NULL,   -- e.g. SS-000001
  user_hash        STRING    NOT NULL,   -- salted hash of the Telegram user id
  customer_name    STRING,
  contact          STRING,               -- e-mail; needed to deliver the receipt
  product_id       INT64,
  quantity         INT64     NOT NULL,
  items            STRING    NOT NULL,   -- human-readable description
  base_amount      NUMERIC   NOT NULL,   -- without tax
  tax_amount       NUMERIC   NOT NULL,
  total_amount     NUMERIC   NOT NULL,   -- what the customer pays for the products
  shipping_fee     NUMERIC   NOT NULL,
  status           STRING    NOT NULL,   -- validated | in_progress | delivered | refunded
  sale_ref_ticket  STRING,               -- original ticket for refunds and exchanges
  comment          STRING,
  created_at       TIMESTAMP NOT NULL
);

-- ---------------------------------------------------------------------
-- Returned pairs. They never go back to sellable stock.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS stride_soul.returns (
  return_id        STRING    NOT NULL,
  original_ticket  STRING    NOT NULL,
  product_id       INT64,
  quantity         INT64     NOT NULL,
  type             STRING    NOT NULL,   -- refund | exchange
  destination      STRING    NOT NULL,   -- recovery_partner
  reason           STRING,
  created_at       TIMESTAMP NOT NULL
);

-- ---------------------------------------------------------------------
-- Cases the agent escalates to a person. Contact is mandatory.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS stride_soul.support_cases (
  case_id          INT64     NOT NULL,   -- shown to the customer as 0001, 0002...
  user_hash        STRING    NOT NULL,
  customer_name    STRING,
  contact          STRING    NOT NULL,
  reason           STRING,
  escalation_type  STRING    NOT NULL,   -- supervisor_request | legal_mention | incomplete_delivery | damaged_product | staff_complaint | other
  triage_area      STRING    NOT NULL,   -- product | store | staff | policies | other
  ticket_no        STRING,               -- set when the case is about a purchase
  attended         BOOL      NOT NULL,
  created_at       TIMESTAMP NOT NULL
);

-- ---------------------------------------------------------------------
-- Process events: one row each time a conversation reaches a stage.
-- This is the stage-by-stage funnel used to find bottlenecks.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS stride_soul.conversation_events (
  event_id      STRING    NOT NULL,
  session_id    STRING    NOT NULL,     -- user_hash + conversation start
  user_hash     STRING    NOT NULL,
  stage         STRING    NOT NULL,     -- start | catalog_query | data_validated | sale_registered | support_case | refund | exchange | contingency
  event_ts      TIMESTAMP NOT NULL,
  execution_id  STRING,
  details       JSON
)
PARTITION BY DATE(event_ts)
CLUSTER BY stage;

-- ---------------------------------------------------------------------
-- Audit log: one row per conversation turn, PII masked before insert.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS stride_soul.audit_logs (
  log_id          STRING    NOT NULL,
  user_hash       STRING    NOT NULL,
  input           STRING,
  output          STRING,
  validation      STRING,               -- ok | email_valid | email_invalid | no_validation
  slots_snapshot  JSON,                 -- e.g. {"name":"Kevin","email":"kev***@gmail.com"}
  summary         STRING,
  created_at      TIMESTAMP NOT NULL
)
PARTITION BY DATE(created_at);

-- ---------------------------------------------------------------------
-- Execution metrics: one row per workflow execution (Playbook §2.1).
-- Written by the Register_Metric sub-workflow and the Error Workflow.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS stride_soul.execution_metrics (
  logged_at      TIMESTAMP NOT NULL,
  execution_id   STRING    NOT NULL,
  workflow       STRING    NOT NULL,
  status         STRING    NOT NULL,    -- success | error | invalid_response
  started_at     TIMESTAMP,
  finished_at    TIMESTAMP,
  duration_s     FLOAT64,
  node           STRING,                -- failing node, empty on success
  error          STRING,                -- sanitised error message
  user_hash      STRING,                -- never a raw e-mail or phone
  registered_by  STRING    NOT NULL     -- MAIN_FLOW | ERROR_HANDLER
)
PARTITION BY DATE(logged_at)
CLUSTER BY workflow, status;
